import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const source = readFileSync(resolve(root, 'resources/database/eleckoi-common-schema-v1.sql'), 'utf8').replaceAll('\r\n', '\n')
const camel = (value) => value.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase())
const tables = [...source.matchAll(/^CREATE TABLE IF NOT EXISTS `([^`]+)` \((.+)\);$/gm)]
if (tables.length === 0) throw new Error('Canonical common schema contains no business tables')
const header = '// Generated by scripts/generate-common-schema.mjs. Edit the canonical SQL snapshot, then regenerate.\n'
const mappings = [header, "import { sql } from 'drizzle-orm'", "import { integer, real, text, primaryKey, sqliteTable } from 'drizzle-orm/sqlite-core'", '']
const types = new Set()
for (const [, name, body] of tables) {
  const fields = [...body.matchAll(/(?:^|, )`([^`]+)` (TEXT|INTEGER|REAL)( NOT NULL)?(?: DEFAULT ('[^']*'|[^,]+))?/g)]
  const keys = [...body.match(/PRIMARY KEY\(([^)]+)\)/)[1].matchAll(/`([^`]+)`/g)].map((m) => m[1])
  mappings.push(`export const ${camel(name)} = sqliteTable('${name}', {`)
  for (const [, column, affinity, required, defaultSql] of fields) {
    const type = affinity.toLowerCase()
    types.add(type)
    const nullable = required ? '.notNull()' : ''
    const primary = keys.length === 1 && keys[0] === column ? '.primaryKey()' : ''
    const fallback = defaultSql === undefined ? '' : `.default(sql.raw(${JSON.stringify(defaultSql)}))`
    mappings.push(`  ${column}: ${type}('${column}')${nullable}${primary}${fallback},`)
  }
  mappings.push(keys.length > 1 ? `}, (table) => [primaryKey({ columns: [${keys.map((k) => `table.${k}`).join(', ')}] })])` : '})', '')
}
if (!types.has('real')) mappings[2] = mappings[2].replace('real, ', '')
mappings.push(`export const commonTables = { ${tables.map(([, name]) => camel(name)).join(', ')} }`, '')
const outputs = new Map([
  ['src/main/platform/sqlite/schema/common.ts', mappings.join('\n')],
  ['src/main/platform/sqlite/migrations/commonSchemaSql.ts', header + `export const commonSchemaSql = ${JSON.stringify(source)}\n`]
])
for (const [path, content] of outputs) {
  const file = resolve(root, path)
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8') !== content) throw new Error(`Stale generated database mapping: ${path}`)
  } else writeFileSync(file, content)
}
const viewCount = [...source.matchAll(/^CREATE VIEW\s+/gm)].length
console.log(`Common SQLite ${process.argv.includes('--check') ? 'check' : 'generation'} passed: ${tables.length} tables, ${viewCount} views.`)
